def slide_mark(number):
    """Выделенная строка: на этом месте нужно переключить слайд."""
    p = d.para("")
    run = p.add_run(f"▶ Слайд {number}: {SLIDES[number]}")
    _set_font(run, bold=True)
    run.font.highlight_color = WD_COLOR_INDEX.YELLOW


d.para("Жёлтая строка означает момент, когда нужно переключить слайд. Голубым выделены шаги речи.")
for title, text in SPEECH:
    d.blue(title)
    for part in re.split(r"(\[\[\d+\]\])", text):
        if part.startswith("[["):
            slide_mark(int(part[2:-2]))
        elif part.strip():
            d.para(part.strip())
d.heading2("Где что открыть, если попросят показать")
